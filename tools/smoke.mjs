import { ethers } from 'ethers';
const API = 'https://rookery.stinkypenguin.xyz/api';
let pass = 0, fail = 0;
const ok = (n, v, x = '') => { v ? pass++ : fail++; console.log(`  ${v ? 'PASS' : 'FAIL'} ${n}${x ? ' — ' + x : ''}`); };
let cookie = '';
const call = async (m, p, b) => { const r = await fetch(API + p, { method: m, headers: { 'content-type': 'application/json', 'x-pl': '1', cookie }, body: b ? JSON.stringify(b) : undefined }); const sc = r.headers.get('set-cookie'); if (sc) cookie = sc.split(';')[0]; return r.json().catch(() => ({ error: 'http ' + r.status })); };
const g = async (p) => (await call('GET', p + (p.includes('?') ? '&' : '?') + 'r=' + Math.random()));

const st = await g('/stats');
ok('stats live', st.markets > 0, st.markets + ' markets');
ok('LitVM listed', !!st.networks?.litvm, JSON.stringify(st.networks?.litvm || {}).slice(0, 80));
ok('LTC price', st.ltcUsd > 0, '$' + st.ltcUsd);
const rh = await g('/rh/config');
ok('Robinhood chain config', rh.live === true && rh.zap === true, 'curve ' + (rh.curve || '').slice(0, 10));
ok('Robinhood pairs listed', (rh.quotes || []).length > 100, (rh.quotes || []).length + ' assets');
const pr = await g('/proofs');
ok('proofs LTC block', pr.ltc && typeof pr.ltc.held === 'number' && 'coverage' in (pr.ltc || {}), JSON.stringify(pr.ltc || {}).slice(0, 90));
ok('proofs ETH + stellar', pr.eth?.owed >= 0 && pr.stellar?.owed >= 0);
const bc = await g('/bridge/config');
const nets = Object.keys(bc.networks || bc.nets || {});
ok('bridge has Litecoin', nets.includes('litecoin'), nets.length + ' networks');
const q1 = await call('POST', '/bridge/quote', { from: 'litecoin', to: 'stellar', amount: '0.05', recipient: 'GDZWHJSSMSQF2GU5S7V4WOJY7BEZUQI3PFHKNK3AHEEFLVNEKG3QX3NI', dry: true });
ok('LTC -> XLM quote', !!q1.quote, q1.error || q1.quote?.amountOutFmt + ' XLM');
const q2 = await call('POST', '/bridge/quote', { from: 'stellar', to: 'litecoin', amount: '5', recipient: 'ltc1qd9an6js0wnkslxr4f2r9lxkda3d9zkxtg4jcx8', dry: true });
ok('XLM -> LTC quote', !!q2.quote, q2.error || q2.quote?.amountOutFmt + ' LTC');
const w = ethers.Wallet.createRandom();
const n = await call('POST', '/auth/wallet/nonce', { address: w.address });
const lg = await call('POST', '/auth/wallet/verify', { nonce: n.nonce, signature: await w.signMessage(n.message) });
ok('wallet login', !!lg.username, lg.username);
const a1 = await call('GET', '/ltc/address'), a2 = await call('GET', '/ltc/address');
ok('fixed LTC address', a1.address?.startsWith('ltc1') && a1.address === a2.address, a1.address || a1.error);
const me = await call('GET', '/me');
ok('account has LTC fields', me.ltcAddress === a1.address && me.ltc !== undefined && me.zltc !== undefined);
const lm = await g('/markets?network=litvm');
ok('Explore LitVM endpoint', Array.isArray(lm.markets));
const errs = await g('/admin/health?key=' + (process.env.ADMIN_KEY || ''));
ok('cron errors empty', JSON.stringify(errs.cronReport?.scanErrors || {}) === '{}', JSON.stringify(errs.cronReport?.scanErrors || {}));
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
